#!/usr/bin/env python3
"""Render the E10 stronger-baseline table from code/e5_stats.py output
(run with --conditions direct structured situation chain_of_thought self_reflection
 --bases chain_of_thought self_reflection structured)."""
import argparse
import json
from pathlib import Path

NAMES = {"nemotron-3-ultra-550b-a55b": "Nemotron-3-Ultra", "dots-3-note-preview": "dots-3-note",
         "flint-v1.0": "Flint-v1.0"}
COLS = ("structured", "chain_of_thought", "self_reflection", "situation")
BASES = ("chain_of_thought", "self_reflection")


def num(x):
    return f"{100 * x:+.1f}".replace("-", "$-$")


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--stats", default="paper/results/e10_stats.json")
    p.add_argument("--out", default="paper/section/tables/e10_baselines_table.tex")
    a = p.parse_args()
    s = json.loads(Path(a.stats).read_text())
    rows = []
    for m, r in s["models"].items():
        name = m.split("/")[-1].replace(":free", "")
        acc = " & ".join(f"{100 * r['conditions'][c]['accuracy']:.1f}" for c in COLS)
        con = [r["contrasts"][f"situation_minus_{b}"] for b in BASES]
        rows.append(f"{NAMES.get(name, name)} & {acc} & " + " & ".join(num(c["delta"]) for c in con) + r" \\")
        rows.append(r"{\scriptsize 95\% CI} & & & & & " + " & ".join(
            r"{\scriptsize [" + num(c["ci95"][0]) + ", " + num(c["ci95"][1]) + "]}" for c in con)
            + r" \\" + "\n" + r"\addlinespace[2pt]")
    tex = r"""% Generated by code/make_e10_table.py; do not edit.
\begin{table}[t]
\caption{E10: stronger prompting baselines on the $n=210$ sample (free model endpoints).
Accuracy (\%) of the structured, chain-of-thought (CoT), self-reflection (Refl.) and
situation prompts, and the paired situation$-$CoT and situation$-$Refl.\ contrasts in
percentage points with 95\% category-clustered bootstrap intervals. Structured and
situation records are those of E8a, collected some days earlier on the same endpoints.}
\label{tab:e10-baselines}
\centering\footnotesize\setlength{\tabcolsep}{3.5pt}%
\begin{tabular}{lrrrrrr}
\toprule
Model & Struct. & CoT & Refl. & Sit. & Sit.$-$CoT & Sit.$-$Refl. \\
\midrule
""" + "\n".join(rows) + r"""
\botrule
\end{tabular}
\end{table}
"""
    Path(a.out).write_text(tex)
    print(f"Wrote {a.out}")


if __name__ == "__main__":
    main()
