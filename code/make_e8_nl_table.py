#!/usr/bin/env python3
"""Render the E8b SituatedQA table from code/e8_nl_stats.py output."""
import argparse
import json
from pathlib import Path

p = argparse.ArgumentParser()
p.add_argument("--stats", default="paper/results/e8_nl_stats.json")
p.add_argument("--out", default="paper/section/tables/e8_nl_table.tex")
a = p.parse_args()
s = json.loads(Path(a.stats).read_text())


def num(x):
    return f"{x:+.1f}".replace("-", "$-$")


def est(c):
    return num(c["estimate_pp"])


def ci(c):
    return r"{\scriptsize [" + num(c["ci_pp"][0]) + ", " + num(c["ci_pp"][1]) + "]}"


KEYS = ("nl_h1_situation_minus_structured", "nl_h2_dated_minus_undated_time_dependent",
        "nl_h2_dated_minus_undated_static_control")
rows = []
for m, r in s["models"].items():
    acc = r["accuracy_pct"]
    name = m.split("/")[-1].replace(":free", "")
    name = {"nemotron-3-ultra-550b-a55b": "Nemotron-3-Ultra", "dots-3-note-preview": "dots-3-note"}.get(name, name)
    rows.append(rf"{name} & {acc['direct']:.1f} & {acc['date_context']:.1f} & "
                rf"{acc['structured']:.1f} & {acc['situation']:.1f} & "
                + " & ".join(est(r[k]) for k in KEYS) + r" \\")
    rows.append(r"{\scriptsize 95\% CI} & & & & & " + " & ".join(ci(r[k]) for k in KEYS)
                + r" \\" + "\n" + r"\addlinespace[2pt]")
n = next(iter(s["models"].values()))["n"]
tex = r"""% Generated by code/make_e8_nl_table.py; do not edit.
\begin{table}[t]
\caption{E8b: natural-text temporal questions (SituatedQA test split, $n=""" + str(n) + r"""$,
75 per date type; free model endpoints). Accuracy (\%) for the undated question
(Undated), the dated question with the same prompt (Dated), and the structured
and situation prompts on the dated question. Contrasts are paired differences in
percentage points with 95\% bootstrap intervals clustered on the source question:
situation$-$structured on all items (H1), and dated$-$undated on time-dependent
items (H2, $n=225$) and on control items dated at the dataset's collection year
(Ctrl, $n=75$).}
\label{tab:e8-nl}
\centering\footnotesize\setlength{\tabcolsep}{3.5pt}%
\begin{tabular}{lrrrrrrr}
\toprule
Model & Undated & Dated & Struct. & Sit. & H1 & H2 & Ctrl \\
\midrule
""" + "\n".join(rows) + r"""
\botrule
\end{tabular}
\end{table}
"""
Path(a.out).write_text(tex)
print(f"Wrote {a.out}")
