#!/usr/bin/env python3
"""Render the E9 SituatedQA geographic table from code/e9_geo_stats.py output."""
import argparse
import json
from pathlib import Path

NAMES = {"nemotron-3-ultra-550b-a55b": "Nemotron-3-Ultra", "dots-3-note-preview": "dots-3-note"}
KEYS = ("geo_h1_situation_minus_structured", "geo_h2_located_minus_unlocated")


def num(x):
    return f"{x:+.1f}".replace("-", "$-$")


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--stats", default="paper/results/e9_geo_stats.json")
    p.add_argument("--out", default="paper/section/tables/e9_geo_table.tex")
    a = p.parse_args()
    s = json.loads(Path(a.stats).read_text())
    rows = []
    for m, r in s["models"].items():
        acc = r["accuracy_pct"]
        name = m.split("/")[-1].replace(":free", "")
        rows.append(f"{NAMES.get(name, name)} & {acc['direct']:.1f} & {acc['location_context']:.1f} & "
                    f"{acc['structured']:.1f} & {acc['situation']:.1f} & "
                    + " & ".join(num(r[k]["estimate_pp"]) for k in KEYS) + r" \\")
        rows.append(r"{\scriptsize 95\% CI} & & & & & "
                    + " & ".join(r"{\scriptsize [" + num(r[k]["ci_pp"][0]) + ", " + num(r[k]["ci_pp"][1]) + "]}"
                                 for k in KEYS) + r" \\" + "\n" + r"\addlinespace[2pt]")
    first = next(iter(s["models"].values()))
    tex = r"""% Generated by code/make_e9_geo_table.py; do not edit.
\begin{table}[t]
\caption{E9: natural-text geographic questions (SituatedQA test split, $n=""" + str(first["n"]) + r"""$,
""" + str(first["clusters"]) + r""" source questions; free model endpoints). Accuracy (\%) for the unlocated
question (Unlocated), the located question with the same prompt (Located), and the
structured and situation prompts on the located question. Contrasts are paired
differences in percentage points with 95\% bootstrap intervals clustered on the source
question: situation$-$structured (H1) and located$-$unlocated (H2).}
\label{tab:e9-geo}
\centering\footnotesize\setlength{\tabcolsep}{3.5pt}%
\begin{tabular}{lrrrrrr}
\toprule
Model & Unlocated & Located & Struct. & Sit. & H1 & H2 \\
\midrule
""" + "\n".join(rows) + r"""
\botrule
\end{tabular}
\end{table}
"""
    Path(a.out).write_text(tex)
    print(f"Wrote {a.out}")


if __name__ == "__main__":
    main()
