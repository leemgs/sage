#!/usr/bin/env python3
"""Regenerate the E5 baseline comparison table from archived, rescored JSONL."""
from __future__ import annotations
import argparse, json
from collections import defaultdict
from pathlib import Path

ORDER = ["temporal", "observer", "counterfactual", "scope", "source_conflict", "modality", "hidden_premise"]
LABEL = {"temporal":"Temporal", "observer":"Observer", "counterfactual":"Counterfact.", "scope":"Scope", "source_conflict":"Source confl.", "modality":"Modality", "hidden_premise":"Hidden prem."}
# Column order: retrieval baseline, two full-evidence prompts, tool-using agent.
ALL_COLS = ["direct", "structured", "situation", "agent"]
HEAD = {"direct":"RAG (no metadata)", "structured":"Structured", "situation":"Situation", "agent":"Agent"}

def read(paths, wanted, categories, per_model=None):
    values = defaultdict(list); seen=set()
    for path in paths:
        for line in path.read_text().splitlines():
            if not line.strip(): continue
            r=json.loads(line); key=(r.get("model"), r.get("condition"), r.get("id"))
            if r.get("error") is not None or r.get("condition") not in wanted or key in seen: continue
            seen.add(key); values[(categories[r["id"]], r["condition"])].append(int(r["correct"]))
            if per_model is not None: per_model[(r["model"], categories[r["id"]], r["condition"])].append(int(r["correct"]))
    return values

def pct(xs): return 100 * sum(xs) / len(xs)
def main():
    p=argparse.ArgumentParser()
    p.add_argument("--rag-dir",default="paper/results/raw_rag")
    p.add_argument("--full-dir",default="paper/results/raw")
    p.add_argument("--agent-dir",default="paper/results/raw_agent")
    p.add_argument("--data",default="paper/data/situationcatch_llm_sample.jsonl")
    p.add_argument("--out",default="paper/section/tables/e5_rag_table.tex")
    p.add_argument("--prefix",default="gemini_",help="model-slug prefix of the raw files")
    p.add_argument("--models-text",default="the three Gemini models")
    p.add_argument("--label",default="tab:e5-rag")
    p.add_argument("--file-prefix",default="e5_",help="file prefix of the RAG/full raw files")
    p.add_argument("--no-agent",action="store_true",help="omit the agent column (no agent run)")
    p.add_argument("--json-out",help="also write per-model, per-category accuracy (%%) as JSON")
    p.add_argument("--note",default="Descriptively, on the two categories that most require reasoning over the applicability state -- temporal validity and observer knowledge -- the full-evidence conditions score above both retrieval and the agent; this category-level pattern is exploratory, and none of the retrieval-, prompt-, or tool-based interventions dominates overall.")
    a=p.parse_args()
    categories={r["id"]:r["category"] for r in map(json.loads, Path(a.data).read_text().splitlines())}
    COLS=[c for c in ALL_COLS if not (a.no_agent and c=="agent")]
    dirs={"rag":(a.rag_dir,a.file_prefix),"full":(a.full_dir,a.file_prefix)}
    if not a.no_agent: dirs["agent"]=(a.agent_dir,"agent_")
    files={k:sorted(Path(d).glob(f"{p}{a.prefix}*.jsonl")) for k,(d,p) in dirs.items()}
    n_models={len(v) for v in files.values()}
    if len(n_models)!=1 or 0 in n_models: raise SystemExit(f"model files differ across conditions: { {k:len(v) for k,v in files.items()} }")
    per_cat=30*n_models.pop()
    pm=defaultdict(list)
    rag=read(files["rag"], {"direct"}, categories, pm)
    full=read(files["full"], {"structured","situation"}, categories, pm)
    agent=read(files["agent"], {"agent"}, categories, pm) if "agent" in files else {}
    def get(cat, cond):
        return {"direct":rag, "structured":full, "situation":full, "agent":agent}[cond][(cat, cond)]
    rows=[]; totals={c:[] for c in COLS}
    for cat in ORDER:
        vals={c:get(cat,c) for c in COLS}
        if any(len(x)!=per_cat for x in vals.values()): raise SystemExit(f"incomplete {cat}: "+str({k:len(v) for k,v in vals.items()}))
        for c,x in vals.items(): totals[c]+=x
        cells=" & ".join(f"{pct(vals[c]):.1f}" for c in COLS)
        rows.append(f"{LABEL[cat]} & {cells} \\\\")
    ov=" & ".join(f"{pct(totals[c]):.1f}" for c in COLS)
    header=" & ".join(HEAD[c] for c in COLS)
    tex=(r"""% Generated by code/make_rag_table.py from archived rescored raw; do not edit.
\begin{table}[t]
\caption{Retrieval-augmented (RAG)"""+(", full-evidence prompting, and a tool-using agent" if "agent" in COLS else " and full-evidence prompting")+r""", mean accuracy over """+a.models_text+r""" on the $n=210$ sample. RAG answers from the top-3 lexically retrieved claims, which for these items are all of the item's claims as plain text in time order without timestamps or other metadata; Structured and Situation see all claims with their metadata"""+("; Agent may issue its own search queries over the item's claims before answering. " if "agent" in COLS else ". ")+r""""""+a.note+r"""}
\label{"""+a.label+r"""}
\centering\small\setlength{\tabcolsep}{5pt}%
\begin{tabular}{l"""+"r"*len(COLS)+r"""}
\toprule
Category & """+header+r""" \\
\midrule
"""+"\n".join(rows)+r"""
\midrule
Overall & """+ov+r""" \\
\bottomrule
\end{tabular}
\end{table}
""")
    Path(a.out).write_text(tex); print(f"Wrote audited comparison ({', '.join(COLS)}) to {a.out}")
    if a.json_out:
        out=defaultdict(lambda: defaultdict(dict))
        for (m,cat,cond),xs in sorted(pm.items()):
            out[m][cond if cond!="direct" else "rag_no_metadata"][cat]=round(pct(xs),1)
        Path(a.json_out).write_text(json.dumps(out,indent=2)+"\n"); print(f"Wrote per-model accuracy to {a.json_out}")
if __name__=="__main__": main()
