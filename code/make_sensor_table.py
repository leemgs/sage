#!/usr/bin/env python3
"""Render the E7 LLM-sensor comparison table from code/score_llm_sensor.py output.

Usage: python code/make_sensor_table.py \
          --summary paper/results/llm_sensor_summary.json \
          --out paper/section/tables/e7_sensor_table.tex
"""
import argparse
import json
from pathlib import Path

SLOT_COLS = [("actor", "Actor"), ("event", "Event"), ("scope", "Scope"),
             ("modality", "Modality"), ("source_status", "Source"),
             ("observer_knowledge", "Observer"), ("world", "World"),
             ("time", "Time")]


def name(model):
    return model.split("/")[-1]


def row(label, r):
    slots = " & ".join(f"{100 * r['slot_accuracy'][k]:.1f}" for k, _ in SLOT_COLS)
    return f"{label} & {100 * r['end_to_end_accuracy']:.1f} & {slots} \\\\"


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--summary", default="paper/results/llm_sensor_summary.json")
    p.add_argument("--out", default="paper/section/tables/e7_sensor_table.tex")
    a = p.parse_args()
    s = json.loads(Path(a.summary).read_text())
    rows = [row("Rule-based", s["rule_sensor"])]
    rows += [row(r"\texttt{" + name(m).replace("_", r"\_") + "}", r)
             for m, r in sorted(s["models"].items())]
    head = " & ".join(h for _, h in SLOT_COLS)
    tex = (r"""% Generated by code/make_sensor_table.py; do not edit.
\begin{table}[t]
\caption{E7: LLMs as situation sensors on the $n=""" + str(s["n_items"]) + r"""$ E5 items.
Every sensor receives only the query time, question and claim texts; its state
is passed unchanged to the SCQA engine. End-to-end is exact action-and-answer
accuracy (\%); the other columns are claim-level slot accuracy (\%), scored
identically for all sensors. Claim texts state no times, so Time is
unrecoverable by design.}
\label{tab:e7-sensor}
\centering\footnotesize\setlength{\tabcolsep}{3pt}%
\begin{tabular}{lr""" + "r" * len(SLOT_COLS) + r"""}
\toprule
Sensor & End-to-end & """ + head + r""" \\
\midrule
""" + "\n".join(rows) + r"""
\botrule
\end{tabular}
\end{table}
""")
    Path(a.out).write_text(tex)
    print(f"Wrote {a.out}")


if __name__ == "__main__":
    main()
